// Writes results/fever.json and results/fever.md from the frozen scenario in
// scripts/scenarios/fever.json, results/summary.json and results/summary.md
// for every scenario (frozen seed plus 100 seeds), and results/sensitivity.json
// and results/sensitivity.md for the fever sensitivity grid. Run with `npm run evaluate`.
// Same scenarios and same status rules in, same files out, every run.

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  buildSummary,
  evaluateScenario,
  type CountStat,
  type DayStat,
  type Scenario,
  type ScenarioResult,
  type Sensitivity,
  type SensitivityConfig,
  type Summary,
  buildSensitivity,
} from "./scenario";
import scenarioJson from "./scenarios/fever.json";
import sensitivityJson from "./scenarios/sensitivity.json";

const scenario = scenarioJson as Scenario;

// A missing first alert is shown as "none", not as 0.
function dayText(day: number | null): string {
  return day === null ? "none" : String(day);
}

function toMarkdown(result: ScenarioResult): string {
  const rows = result.methods.map(
    (m) =>
      `| ${m.label} | ${dayText(m.firstAmberDay)} | ${dayText(m.firstRedDay)} | ${m.missed} | ${m.falseAmber} | ${m.falseRed} |`,
  );

  const trace = result.trace.map(
    (row) =>
      `| ${row.missionDay} | ${row.dayAfterOnset ?? ""} | ${row.value.toFixed(scenario.decimals)} | ${row.statuses.earthRange} | ${row.statuses.adjustedRange} | ${row.statuses.adjustedRangeAndBaseline} |`,
  );

  return [
    "# Alert test: slow-onset fever",
    "",
    "Generated by `npm run evaluate` from `scripts/scenarios/fever.json`. Do not edit by hand.",
    "",
    `Simulated ${scenario.environment} mission, days ${scenario.firstMissionDay} to ${scenario.firstMissionDay + scenario.days - 1}: ${result.healthyDays} healthy days at ${scenario.base} ± ${scenario.noise} ${scenario.unit}, then a rise of ${scenario.risePerDay} ${scenario.unit} per day for ${result.feverDays} days from mission day ${scenario.feverStartMissionDay}.`,
    "",
    "## Results",
    "",
    "| Method | First amber (days after onset) | First red (days after onset) | Missed (fever readings left green) | False amber (healthy period) | False red (healthy period) |",
    "|---|---|---|---|---|---|",
    ...rows,
    "",
    "The onset day is day 0. \"none\" means the method never gave that status during the fever.",
    "",
    "## What we expected before running it",
    "",
    ...scenario.expected.map((line) => `- ${line}`),
    "",
    "## Limits",
    "",
    "- This is a software test of the status rules on one simulated scenario. It is not clinical validation.",
    "- All three methods run the same `getStatus` function the dashboard uses.",
    "- The scenario and its expectations were committed before the evaluation was first run.",
    "- Every scenario value is a demo parameter chosen by the team.",
    "",
    "## Status per reading",
    "",
    "| Mission day | Days after onset | Reading | Earth range only | Adjusted range | Adjusted range and baseline |",
    "|---|---|---|---|---|---|",
    ...trace,
    "",
  ].join("\n");
}

// npm scripts always run from the project root, so this path is stable.
const RESULTS_DIR = join(process.cwd(), "results");

function dayStatText(s: DayStat, seedCount: number): string {
  if (s.mean === null) return "none";
  const never = s.never ? ` (none in ${s.never} of ${seedCount})` : "";
  return `${s.mean} / ${s.worst}${never}`;
}

function countStatText(s: CountStat): string {
  return `${s.mean} / ${s.worst}`;
}

function summaryMarkdown(summary: Summary): string {
  const headline = summary.scenarios.flatMap((entry) =>
    entry.frozen.methods.map((m, i) => {
      const multi = entry.multiSeed.methods[i];
      return `| ${entry.title} | ${m.label} | ${dayText(m.firstAmberDay)} | ${dayText(m.firstRedDay)} | ${m.missed} | ${m.falseAmber + m.falseRed} | ${dayStatText(multi.firstAmberDay, entry.multiSeed.seedCount)} | ${dayStatText(multi.firstRedDay, entry.multiSeed.seedCount)} | ${countStatText(multi.missed)} | ${countStatText(multi.falseAmber)} | ${countStatText(multi.falseRed)} |`;
    }),
  );
  const sections = summary.scenarios.flatMap((entry) => [
    `### ${entry.title}`,
    "",
    entry.scenario.note,
    "",
    "What we expected before running it:",
    "",
    ...entry.scenario.expected.map((line) => `- ${line}`),
    "",
  ]);
  return [
    "# Alert test: all scenarios",
    "",
    "Generated by `npm run evaluate` from `scripts/scenarios/`. Do not edit by hand.",
    "",
    `Each scenario runs once with its frozen seed, then with ${summary.seedCount} seeds (the frozen seed and the ${summary.seedCount - 1} after it). Days are counted from the onset day, which is day 0. \"none\" means the method never gave that status. Many-seed columns show mean / worst.`,
    "",
    "## Headline table",
    "",
    "| Scenario | Method | First amber | First red | Missed | False alerts | First amber, mean / worst | First red, mean / worst | Missed, mean / worst | False amber, mean / worst | False red, mean / worst |",
    "|---|---|---|---|---|---|---|---|---|---|---|",
    ...headline,
    "",
    "## Limits",
    "",
    "- This is a software test of the status rules on simulated scenarios. It is not clinical validation.",
    "- All three methods run the same `getStatus` function the dashboard uses.",
    "- Sleep and mood have no spaceflight adjustment and no personal baseline in our rules, so all three methods give the same result for them.",
    "- Every scenario value is a demo parameter chosen by the team.",
    "",
    "## Scenarios",
    "",
    ...sections,
  ].join("\n");
}

const result = evaluateScenario(scenario);
mkdirSync(RESULTS_DIR, { recursive: true });
writeFileSync(
  join(RESULTS_DIR, "fever.json"),
  JSON.stringify(result, null, 2) + "\n",
);
writeFileSync(join(RESULTS_DIR, "fever.md"), toMarkdown(result));
console.log(`Wrote results/fever.json and results/fever.md`);
for (const m of result.methods) {
  console.log(
    `${m.label}: first amber ${dayText(m.firstAmberDay)}, first red ${dayText(m.firstRedDay)}, missed ${m.missed}, false amber ${m.falseAmber}, false red ${m.falseRed}`,
  );
}

const summary = buildSummary();
writeFileSync(join(RESULTS_DIR, "summary.json"), JSON.stringify(summary, null, 2) + "\n");
writeFileSync(join(RESULTS_DIR, "summary.md"), summaryMarkdown(summary));
console.log(`Wrote results/summary.json and results/summary.md (${summary.scenarios.length} scenarios, ${summary.seedCount} seeds each)`);

function sensitivityMarkdown(sensitivity: Sensitivity): string {
  const { config, points, checks } = sensitivity;
  const rows = points.flatMap((point) =>
    point.result.methods.map(
      (m) =>
        `| ${point.noise} | ${point.risePerDay} | ${m.label} | ${dayStatText(m.firstAmberDay, point.result.seedCount)} | ${dayStatText(m.firstRedDay, point.result.seedCount)} | ${countStatText(m.missed)} | ${countStatText({ mean: Math.round((m.falseAmber.mean + m.falseRed.mean) * 100) / 100, worst: Math.max(m.falseAmber.worst, m.falseRed.worst) })} |`,
    ),
  );
  return [
    "# Alert test: fever sensitivity grid",
    "",
    "Generated by `npm run evaluate` from `scripts/scenarios/sensitivity.json` and `scripts/scenarios/fever.json`. Do not edit by hand. The protocol is in `plan/EVALUATION.md`, section 8.",
    "",
    `The fever scenario rerun with every combination of noise (${config.noise.join(", ")} °C) and rise per day (${config.risePerDay.join(", ")} °C), ${config.seedCount} seeds each: ${points.length * config.seedCount} runs. Everything else is as in fever.json: 30 healthy days at 37.4 °C, then 10 days of fever, Mars transit. Days are counted from the onset day, which is day 0. Columns show mean / worst over the seeds; "none in N" counts the seeds where that status never appeared, and the mean covers only the others.`,
    "",
    "## Predictions",
    "",
    "Committed before this code existed (see `plan/EVALUATION.md`, section 5). Checked automatically by `checkPredictions` in `scripts/scenario.ts`.",
    "",
    "| Prediction | Verdict | Detail |",
    "|---|---|---|",
    ...checks.map((c) => `| ${c.id}: ${c.text} | ${c.verdict} | ${c.detail} |`),
    "",
    "## Limits",
    "",
    "- This is a software test of the status rules on simulated data. It is not clinical validation.",
    "- Only the noise size and the rise speed change. The healthy base, the fever length and the noise shape stay as in fever.json.",
    "- Every value is a demo parameter chosen by the team.",
    "",
    "## Every grid point",
    "",
    "| Noise (°C) | Rise per day (°C) | Method | First amber, mean / worst | First red, mean / worst | Missed, mean / worst | False alerts, mean / worst |",
    "|---|---|---|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
}

const sensitivity = buildSensitivity(sensitivityJson as SensitivityConfig, scenario);
writeFileSync(join(RESULTS_DIR, "sensitivity.json"), JSON.stringify(sensitivity, null, 2) + "\n");
writeFileSync(join(RESULTS_DIR, "sensitivity.md"), sensitivityMarkdown(sensitivity));
console.log(`Wrote results/sensitivity.json and results/sensitivity.md (${sensitivity.points.length} grid points)`);
for (const c of sensitivity.checks) console.log(`${c.id}: ${c.verdict}. ${c.detail}`);
